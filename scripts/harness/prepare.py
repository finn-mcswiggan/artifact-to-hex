#!/usr/bin/env python3
"""Make a node-runnable copy of a Hex generative app, with the Hex runtime stubbed by real data.

  prepare.py <workdir> <outdir> --fixture orders=out/orders.json --fixture regions=out/regions.json \
             [--input selected_account=acme-001]

* copies <workdir>/app to <outdir>, rewrites `app/...` imports to relative paths, drops CSS imports,
  replaces "__CELL:name__" placeholders with "name";
* writes <outdir>/_data.js: useHexData(name) returns the fixture rows (status COMPLETED, rowCount set),
  useHexInput(name) returns {currentValue}, React hooks run synchronously (no effects);
* copies walk.mjs, which renders a component tree to text so a check script can assert on it.

Then write <outdir>/check.mjs (see walk.mjs header) and run `node check.mjs`. Override per test with
globalThis.HEX_INPUTS / HEX_UI / HEX_STATE / HEX_PARTIAL before calling render().
"""
import argparse, json, os, re, shutil

HERE = os.path.dirname(os.path.abspath(__file__))

STUB = r'''// Stub of Hex's app/_data.js runtime for node tests. Generated by prepare.py.
import fs from "node:fs";
const FIXTURES = __FIXTURES__;
const INPUT_DEFAULTS = __INPUTS__;
const cache = {};
function rowsFor(name) {
  if (!(name in FIXTURES)) throw new Error(`no fixture for cell "${name}" (pass --fixture ${name}=file.json)`);
  if (!cache[name]) cache[name] = JSON.parse(fs.readFileSync(new URL(FIXTURES[name], import.meta.url)));
  let rows = cache[name];
  const filter = globalThis.HEX_FILTERS?.[name];          // emulate an input-filtered SQL cell
  if (filter) rows = rows.filter(filter);
  return rows;
}
export const React = {
  createElement: (type, props, ...children) => ({ type, props: props || {}, children: children.flat() }),
  Fragment: "fragment",
  useState: (v) => [globalThis.HEX_STATE ? globalThis.HEX_STATE(v) ?? v : v, () => {}],
  useRef: (v) => ({ current: v }),
  useMemo: (f) => f(),
  useCallback: (f) => f,
  useEffect: () => {},
  useLayoutEffect: () => {},
  useContext: () => undefined,
  createContext: (v) => ({ Provider: "provider", value: v }),
};
export const useHexData = (name) => {
  const rows = rowsFor(name);
  const partial = globalThis.HEX_PARTIAL?.[name];         // emulate rows still arriving
  const shown = partial ? rows.slice(0, partial) : rows;
  return { rows: shown, rowCount: rows.length, status: "COMPLETED", hasData: true, isEmpty: rows.length === 0 };
};
export const useHexInput = (name) => ({ currentValue: globalThis.HEX_INPUTS?.[name] ?? INPUT_DEFAULTS[name] ?? null });
export const setHexInput = (name, value) => { (globalThis.HEX_SET_INPUT_CALLS ||= []).push([name, value]); };
export const useHexUiState = (key, d) => [globalThis.HEX_UI?.[key] ?? d, () => {}];
export const useHexConfig = () => globalThis.HEX_CONFIG || {};
export const render = (el) => { globalThis.HEX_RENDERED = el; };
const passthrough = (tag) => (props) => ({ type: tag, props: props || {}, children: [props?.children].flat().filter(Boolean) });
export const ComponentChrome = passthrough("div");
export const ChartShell = passthrough("div");
export const LucideIcons = new Proxy({}, { get: (_, n) => passthrough("svg") });
export const BaseSelect = passthrough("select"), BaseSwitch = passthrough("button"), BaseTabs = passthrough("div"),
  BaseTooltip = passthrough("span"), BasePopover = passthrough("div"), BaseCombobox = passthrough("div"), DayPicker = passthrough("div");
export const d3 = globalThis.HEX_D3 || null;   // set globalThis.HEX_D3 = await import("d3") if the app uses d3
export const dateFns = globalThis.HEX_DATEFNS || null;
export const useComponentValues = () => ({});
export const useEditEmitter = () => () => {};
export const useChartSubregionEditState = () => [null, () => {}];
'''


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("workdir"); p.add_argument("outdir")
    p.add_argument("--fixture", action="append", default=[]); p.add_argument("--input", action="append", default=[])
    a = p.parse_args()
    src = os.path.join(a.workdir, "app")
    if os.path.exists(a.outdir):
        marker = os.path.join(a.outdir, "_data.js")
        # Only ever overwrite a folder this script generated before, never an arbitrary path.
        if not (os.path.isfile(marker) and "Generated by prepare.py" in open(marker).read()):
            raise SystemExit(f"{a.outdir} exists and was not created by prepare.py; choose a new output folder")
        shutil.rmtree(a.outdir)
    shutil.copytree(src, a.outdir)
    for root, _, names in os.walk(a.outdir):
        for n in names:
            if not n.endswith(".js"):
                continue
            path = os.path.join(root, n)
            depth = os.path.relpath(path, a.outdir).count(os.sep)
            pre = "../" * depth if depth else "./"
            t = open(path).read()
            t = re.sub(r'import\s+"app/[^"]+\.css";\s*\n', "", t)
            t = re.sub(r'from\s+"app/([^"]+)"', lambda m: f'from "{pre}{m.group(1)}"', t)
            t = re.sub(r'import\s+(\w+)\s+from\s+"(\.{1,2}/[^"]+\.json)";',
                       lambda m: f'import {m.group(1)} from "{m.group(2)}" with {{ type: "json" }};', t)
            t = re.sub(r'"__CELL:([A-Za-z0-9_\-]+)__"', r'"\1"', t)
            open(path, "w").write(t)
    fixtures = {}
    for f in a.fixture:
        k, _, v = f.partition("=")
        fixtures[k] = "file://" + os.path.abspath(v)
    inputs = dict(x.split("=", 1) for x in a.input)
    stub = STUB.replace("__FIXTURES__", json.dumps(fixtures)).replace("__INPUTS__", json.dumps(inputs))
    open(os.path.join(a.outdir, "_data.js"), "w").write(stub)
    shutil.copy(os.path.join(HERE, "walk.mjs"), os.path.join(a.outdir, "walk.mjs"))
    print(f"harness ready in {a.outdir}: write check.mjs next to walk.mjs and run `node check.mjs`")


if __name__ == "__main__":
    main()
